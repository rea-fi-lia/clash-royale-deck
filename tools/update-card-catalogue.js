#!/usr/bin/env node
// One command builds every public consumer; no publication before validation.
const fs = require('node:fs');
const path = require('node:path');
const {ROOT,SOURCE,digest,slugOf,readCatalogue,validate,buildManifest} = require('./card-catalogue.cjs');
const arg = key => {const n=process.argv.indexOf(key);return n<0?null:process.argv[n+1];};
function reconcileOfficial(source, api) {
  if (!Array.isArray(api.items) || api.items.length < source.cards.length * .9) throw Error('Incomplete official card list');
  const next = structuredClone(source), issues=[], changes=[];
  const byId=new Map(next.cards.filter(c=>c.id).map(c=>[c.id,c])), bySlug=new Map(next.cards.map(c=>[c.slug,c]));
  const seen=new Set();
  for (const item of api.items) {
    const c=byId.get(item.id)||bySlug.get(slugOf(item.name));
    if (!c) {issues.push({kind:'new-card',id:item.id,name:item.name,cost:item.elixirCost,icons:item.iconUrls});continue;}
    seen.add(c.slug);
    const before=JSON.stringify(c);
    if (!Number.isSafeInteger(item.id)) {issues.push({kind:'invalid-id',slug:c.slug});continue;}
    c.id=item.id;
    c.english=item.name;
    // Mirror's dynamic cost is represented as 1 in CRDB; do not overwrite it with an API sentinel.
    if (c.slug!=='mirror' && Number.isInteger(item.elixirCost) && item.elixirCost>=0) c.cost=item.elixirCost;
    const keys={medium:'n',evolutionMedium:'e',heroMedium:'h'};
    for (const [key,url] of Object.entries(item.iconUrls || {})) {
      const form=keys[key];
      if (!form) {issues.push({kind:'unknown-icon-form',slug:c.slug,key});continue;}
      if (!c.forms[form]) c.forms[form]={image:`https://cdn.royaleapi.com/static/img/cards/${c.slug}${form==='e'?'-ev1':form==='h'?'-hero':''}.png`};
      c.forms[form].officialIcon=url;
    }
    for (const [key,form] of Object.entries(keys)) if (c.forms[form] && !item.iconUrls?.[key]) issues.push({kind:'removed-form',slug:c.slug,form});
    // /cards maxEvolutionLevel=3 is already returned for the four cards with both icons.
    // It is not the same field as a played card's battlelog evolutionLevel.
    const max=item.maxEvolutionLevel || 0;
    if (max>2 && !(max===3 && item.iconUrls?.evolutionMedium && item.iconUrls?.heroMedium)) issues.push({kind:'unknown-evolution-level',slug:c.slug,value:max});
    if (before!==JSON.stringify(c)) changes.push(c.slug);
  }
  for (const c of next.cards) if (!seen.has(c.slug)) issues.push({kind:'missing-official-card',slug:c.slug});
  return {next,issues,changes};
}
async function hashImages(source, fetcher=fetch) {
  const assets=source.cards.flatMap(c=>Object.values(c.forms));
  let cursor=0;
  await Promise.all(Array.from({length:4},async()=>{
    while(cursor<assets.length) {
      const a=assets[cursor++];
      const r=await fetcher(a.image+'?audit='+new Date().toISOString().slice(0,10),{signal:AbortSignal.timeout(12000),cache:'no-store'});
      if(!r.ok || Number(r.headers.get('content-length'))>1048576) throw Error('Image unavailable: '+a.image);
      const b=Buffer.from(await r.arrayBuffer());
      if(b.length<45||b.length>1048576||!b.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10]))||b.subarray(-8,-4).toString()!=='IEND') throw Error('Invalid PNG: '+a.image);
      if(b.readUInt32BE(16)<10 || b.readUInt32BE(20)<10 || b.readUInt32BE(16)*b.readUInt32BE(20)>1048576) throw Error('Invalid image dimensions: '+a.image);
      let offset=8,hasData=false;
      while(offset<b.length) {
        if(offset+12>b.length) throw Error('Truncated PNG: '+a.image);
        const size=b.readUInt32BE(offset),type=b.subarray(offset+4,offset+8).toString();
        if(offset+size+12>b.length || (offset===8 && (type!=='IHDR'||size!==13))) throw Error('Invalid PNG chunks: '+a.image);
        if(type==='IDAT' && size) hasData=true;
        offset+=size+12;
      }
      if(!hasData) throw Error('Missing PNG pixels: '+a.image);
      a.sha256=digest(b);
    }
  }));
}
function outputs(source) {
  const m=buildManifest(source), runtime=fs.readFileSync(path.join(ROOT,'tools/templates/cards-runtime.js'),'utf8');
  const result = new Map([
    ['catalogue/manifest.json',JSON.stringify(m)+'\n'],
    ['js/cards-data.js','/* Generated by tools/update-card-catalogue.js. Edit catalogue/cards.json; helpers: tools/templates/cards-runtime.js. */\nconst CARD_CATALOGUE_REVISION = '+JSON.stringify(m.revision)+';\nconst CARDS = '+JSON.stringify(m.cards,null,2)+';\n'+runtime]
  ]);
  for(const file of fs.readdirSync(ROOT).filter(f=>f.endsWith('.html'))) {
    const body=fs.readFileSync(path.join(ROOT,file),'utf8');
    const next=body.replace(/js\/cards-data\.js(?:\?v=[^"']*)?/g,'js/cards-data.js?v='+digest(m.revision+runtime).slice(0,16));
    if(next!==body || body.includes('js/cards-data.js')) result.set(file,next);
  }
  return result;
}
async function main() {
  let source=readCatalogue();
  if(process.argv.includes('--refresh')) {
    let api;
    if(arg('--official')) api=JSON.parse(fs.readFileSync(arg('--official'),'utf8'));
    else {
      const token=process.env.CR_TOKEN;
      if(!token) throw Error('CR_TOKEN required for official discovery');
      const r=await fetch('https://proxy.royaleapi.dev/v1/cards',{headers:{Authorization:'Bearer '+token},signal:AbortSignal.timeout(15000)});
      if(!r.ok) throw Error('Official cards HTTP '+r.status);
      api=await r.json();
    }
    const result=reconcileOfficial(source,api);
    if(arg('--report')) fs.writeFileSync(arg('--report'),JSON.stringify({issues:result.issues,changed:result.changes},null,2));
    if(result.issues.length) throw Error('Catalogue needs review: '+JSON.stringify(result.issues));
    source=result.next;
  }
  if(process.argv.includes('--images')||process.argv.includes('--refresh')) await hashImages(source);
  validate(source);
  const files=outputs(source);
  if(process.argv.includes('--check')) {
    for(const [name,body] of files) if(fs.readFileSync(path.join(ROOT,name),'utf8')!==body) throw Error('Generated catalogue drift: '+name);
  } else {
    // Nothing is written until every source/image has passed. A failed refresh keeps the last good release.
    fs.writeFileSync(SOURCE,JSON.stringify(source,null,2)+'\n');
    for(const [name,body] of files) fs.writeFileSync(path.join(ROOT,name),body);
  }
  console.log('catalogue '+buildManifest(source).revision+' / '+source.cards.length+' cards / '+source.cards.reduce((n,c)=>n+Object.keys(c.forms).length,0)+' forms');
}
module.exports={reconcileOfficial,hashImages,outputs};
if(require.main===module) main().catch(e=>{console.error(e.message);process.exitCode=1;});
